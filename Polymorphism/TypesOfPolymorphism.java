package Polymorphism;

/*
 * Topic: Types of Polymorphism
 *
 * Definition:
 * Java supports two main types of polymorphism:
 *
 * 1. Compile-Time Polymorphism
 * 2. Runtime Polymorphism
 *
 * Compile-Time Polymorphism:
 * Achieved through Method Overloading.
 * The compiler determines which overloaded method to call.
 *
 * Runtime Polymorphism:
 * Achieved through Method Overriding.
 * The overridden instance method is selected at runtime
 * based on the actual object's class.
 *
 * Compile-Time Polymorphism:
 * - Also called static polymorphism.
 * - Inheritance is not required.
 *
 * Runtime Polymorphism:
 * - Also called dynamic polymorphism.
 * - Requires a subtype relationship for overriding.
 */


public class TypesOfPolymorphism {

    public static void main(String[] args) {

        System.out.println("Types of Polymorphism");
        System.out.println("1. Compile-Time Polymorphism");
        System.out.println("2. Runtime Polymorphism");
    }
}