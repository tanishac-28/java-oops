package Polymorphism;

/*
 * Topic: Introduction to Polymorphism
 *
 * Definition:
 * Polymorphism is one of the four fundamental principles
 * of Object-Oriented Programming (OOP).
 *
 * It allows an entity to take multiple forms and exhibit
 * different behaviours depending on the context.
 *
 * Word Meaning:
 * Poly  = Many
 * Morph = Forms
 *
 * Types of Polymorphism:
 * 1. Compile-Time Polymorphism
 * 2. Runtime Polymorphism
 *
 * Compile-Time Polymorphism:
 * It is achieved through Method Overloading.
 *
 * Runtime Polymorphism:
 * It is achieved through Method Overriding.
 *
 * Advantages:
 * 1. Improves code reusability.
 * 2. Provides flexibility.
 * 3. Supports extensibility.
 * 4. Improves maintainability.
 *
 * Real-Life Example:
 * A person can perform different roles in different situations,
 * such as a student at college and an employee at work.
 */


public class Introduction {
    public static void main(String[] args) {
        
        System.out.println("Introduction to Polymorphism");
        System.out.println("Poly means Many");
        System.out.println("Morph means Forms");
        System.out.println("Polymorsphism means Many Forms");
    }
}
